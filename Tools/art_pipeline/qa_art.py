"""Art coherence QA (critical UX rule CUX-9). Costs nothing. Run after process_art.py:

    set PYTHONPATH=E:/pylibs
    python Tools/art_pipeline/qa_art.py [--montage-dir E:/Unity/qa]

For every sliced sheet (Assets/Art/**/<id>/sprites.json) and single sprite it checks:
  clipped   opaque pixels touch the image edge (the object was cut by the crop)
  halo      semi-transparent pixels still carry the grey key colour (a grey fringe on the sprite)
  tiny      smaller than 24 px on a side
  extreme   width/height ratio above 6 or below 1/6 (outside tilesets) - often a mis-split
  duplicate identical pixels to another sprite of the same sheet
  scale     sheet-internal area ratio above 6 (mixed scales in one sheet)
Writes Assets/Art/QA_REPORT.md and one contact sheet PNG per sheet (checkerboard background, index labels) for visual review.
Exit code 1 when any 'clipped' or 'halo' issue exists, so it can gate a commit.
"""
import hashlib
import json
import os
import sys

sys.path.insert(0, "E:/pylibs")
import numpy as np  # noqa: E402
from PIL import Image, ImageDraw  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ART = os.path.join(ROOT, "Assets", "Art")
TILESET_HINT = ("tileset",)


def checker(w, h, cell=16):
    a = np.zeros((h, w, 3), np.uint8)
    yy, xx = np.mgrid[0:h, 0:w]
    m = ((yy // cell + xx // cell) % 2) == 0
    a[m] = (200, 200, 200)
    a[~m] = (150, 150, 150)
    return Image.fromarray(a)


def analyse(path, key):
    im = Image.open(path).convert("RGBA")
    a = np.asarray(im)
    alpha = a[..., 3]
    issues = []
    h, w = alpha.shape
    edge = np.concatenate([alpha[0, :], alpha[-1, :], alpha[:, 0], alpha[:, -1]])
    if (edge > 128).sum() > 2:
        issues.append("clipped")
    if key is not None:
        semi = (alpha > 8) & (alpha < 200)
        if semi.sum() > 40:
            d = np.abs(a[..., :3].astype(int) - np.array(key)).sum(axis=2)
            frac = ((d < 40) & semi).sum() / semi.sum()
            if frac > 0.35:
                issues.append("halo(%.0f%%)" % (frac * 100))
    if w < 24 or h < 24:
        issues.append("tiny")
    if not any(t in path.lower() for t in TILESET_HINT):
        r = w / max(1, h)
        if r > 6 or r < 1 / 6:
            issues.append("extreme(%.1f)" % r)
    return im, issues, w * h


def montage(images, labels, out, tile=200):
    cols = min(6, max(1, len(images)))
    rows = (len(images) + cols - 1) // cols
    sheet = checker(cols * tile, rows * (tile + 22))
    d = ImageDraw.Draw(sheet)
    for i, (im, lab) in enumerate(zip(images, labels)):
        cx, cy = (i % cols) * tile, (i // cols) * (tile + 22)
        t = im.copy()
        t.thumbnail((tile - 8, tile - 8))
        sheet.paste(t, (cx + (tile - t.width) // 2, cy + 22 + (tile - t.height) // 2), t)
        d.rectangle([cx, cy, cx + tile - 1, cy + 20], fill=(20, 20, 40))
        d.text((cx + 4, cy + 4), lab[:30], fill=(255, 255, 255))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    sheet.convert("RGB").save(out)


def main():
    mdir = "E:/Unity/qa"
    if "--montage-dir" in sys.argv:
        mdir = sys.argv[sys.argv.index("--montage-dir") + 1]
    lines = ["# Art QA report (generated by Tools/art_pipeline/qa_art.py)", ""]
    blocking = 0
    total = 0
    for dirpath, _dirs, files in os.walk(ART):
        if "sprites.json" not in files:
            continue
        info = json.load(open(os.path.join(dirpath, "sprites.json")))
        key = info.get("keyColour")
        asset = info.get("asset", os.path.basename(dirpath))
        pngs = sorted(f for f in files if f.endswith(".png"))
        images, labels, areas, hashes = [], [], [], {}
        sheet_lines = []
        for f in pngs:
            im, issues, area = analyse(os.path.join(dirpath, f), key)
            total += 1
            digest = hashlib.md5(im.tobytes()).hexdigest()
            if digest in hashes:
                issues.append("duplicate of " + hashes[digest])
            hashes[digest] = f
            images.append(im)
            labels.append("%s %s" % (f.rsplit("_", 1)[-1][:-4], ",".join(i.split("(")[0] for i in issues)))
            areas.append(area)
            if issues:
                sheet_lines.append("- `%s` (%dx%d): %s" % (f, im.width, im.height, ", ".join(issues)))
                if any(i.startswith(("clipped", "halo")) for i in issues):
                    blocking += 1
        if areas and max(areas) / max(1, min(areas)) > 6 and "tileset" not in asset:
            sheet_lines.append("- scale: area ratio %.1f between largest and smallest sprite (mixed scales)" % (max(areas) / min(areas)))
        lines.append("## %s  (%d sprites)" % (asset, len(pngs)))
        lines.extend(sheet_lines or ["- ok"])
        lines.append("")
        montage(images, labels, os.path.join(mdir, asset + ".png"))
    lines.append("Sprites checked: %d. Blocking issues (clipped/halo): %d." % (total, blocking))
    with open(os.path.join(ART, "QA_REPORT.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(l for l in lines if l.startswith(("##", "- ", "Sprites")) and not l.endswith("- ok")))
    sys.exit(1 if blocking else 0)


if __name__ == "__main__":
    main()
